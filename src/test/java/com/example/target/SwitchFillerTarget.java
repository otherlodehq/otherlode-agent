package com.example.target;

public class SwitchFillerTarget {

    public int classifyGappy(int value) {
        switch (value) {
            case 1:
                return 1;
            case 2:
                return 2;
            case 3:
                return 3;
            case 5:
                return 5;
            default:
                return -1;
        }
    }
}
