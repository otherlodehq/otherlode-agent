package com.example.target.keypairs;

public class SwitchCaseAddedJavaV2 {
    public String classify(int x) {
        switch (x) {
            case 1:
                return "one";
            case 2:
                return "two";
            case 3:
                return "three";
            case 4:
                return "four";
            default:
                return "other";
        }
    }
}
