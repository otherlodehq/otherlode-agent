package dev.otherlode.instrumentation.endpoints

import dev.otherlode.bootstrap.OtherlodeEndpoints
import dev.otherlode.export.DisabledEndpointModuleKind
import dev.otherlode.instrumentation.endpoints.api.AdviceBinder
import dev.otherlode.instrumentation.endpoints.api.EndpointModule
import dev.otherlode.registry.EndpointRegistry
import net.bytebuddy.agent.ByteBuddyAgent
import net.bytebuddy.agent.builder.ResettableClassFileTransformer
import net.bytebuddy.description.type.TypeDescription
import net.bytebuddy.dynamic.DynamicType
import net.bytebuddy.jar.asm.ClassWriter
import net.bytebuddy.jar.asm.Opcodes
import net.bytebuddy.matcher.ElementMatcher
import net.bytebuddy.matcher.ElementMatchers.nameStartsWith
import java.io.InputStream
import java.lang.instrument.Instrumentation
import kotlin.test.AfterTest
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

/**
 * A module that declares endpoints from inside a transform, on a class whose loader cannot see
 * `dev.otherlode.bootstrap`. Its advice could never count, so the module must declare nothing for
 * that class and report itself disabled, so that no endpoint reads as never called.
 */
class EndpointsInBlindLoaderTest {
    private val instrumentation: Instrumentation = ByteBuddyAgent.install()
    private var installed: EndpointInstrumentation? = null
    private var installedTransformer: ResettableClassFileTransformer? = null

    private companion object {
        const val PACKAGE = "com.example.blindendpoint"
        const val RESOURCE = "$PACKAGE.Resource"

        val RESOURCE_BYTES: ByteArray =
            ClassWriter(0)
                .apply {
                    visit(Opcodes.V17, Opcodes.ACC_PUBLIC or Opcodes.ACC_SUPER, RESOURCE.replace('.', '/'), null, "java/lang/Object", null)
                    visitEnd()
                }.toByteArray()
    }

    private class DeclaringModule : EndpointModule {
        override val name: String = "blind-loader-${System.nanoTime()}"

        override fun typeMatcher(): ElementMatcher<in TypeDescription> = nameStartsWith("$PACKAGE.")

        override fun transform(
            builder: DynamicType.Builder<*>,
            typeDescription: TypeDescription,
            advice: AdviceBinder,
            classLoader: ClassLoader?,
        ): DynamicType.Builder<*> {
            OtherlodeEndpoints.register(name, "${typeDescription.name}#/hello", "GET", "/hello", null, typeDescription.name, null, null)
            return builder
        }
    }

    /** Defines the resource from generated bytes and, like a loader with no boot delegation, resolves nothing under `dev.otherlode.`. */
    private class BlindLoader(
        parent: ClassLoader,
    ) : ClassLoader(parent) {
        override fun loadClass(
            name: String,
            resolve: Boolean,
        ): Class<*> {
            if (name.startsWith("dev.otherlode.")) throw ClassNotFoundException(name)
            if (name != RESOURCE) return super.loadClass(name, resolve)
            synchronized(getClassLoadingLock(name)) {
                val loaded = findLoadedClass(name) ?: defineClass(name, RESOURCE_BYTES, 0, RESOURCE_BYTES.size)
                if (resolve) resolveClass(loaded)
                return loaded
            }
        }

        override fun getResourceAsStream(name: String): InputStream? =
            if (name == RESOURCE.replace('.', '/') + ".class") RESOURCE_BYTES.inputStream() else super.getResourceAsStream(name)
    }

    @AfterTest
    fun tearDown() {
        val transformer = installedTransformer
        if (transformer != null) installed?.uninstall(instrumentation, transformer)
        installed = null
        installedTransformer = null
    }

    @Test
    fun `a module declares nothing for a class whose loader cannot see the bootstrap package and reports itself disabled`() {
        val registry = EndpointRegistry()
        val module = DeclaringModule()
        val endpointInstrumentation = EndpointInstrumentation(registry, listOf(module))
        installed = endpointInstrumentation
        installedTransformer = endpointInstrumentation.install(instrumentation)

        Class.forName(RESOURCE, true, BlindLoader(javaClass.classLoader))

        assertTrue(registry.endpoints().isEmpty(), "${registry.endpoints()}")
        val disabled = registry.disabledModules().single { it.module == module.name }
        assertEquals(DisabledEndpointModuleKind.TRANSFORM_FAILED, disabled.kind)
        assertTrue("cannot see dev.otherlode.bootstrap" in disabled.reason, disabled.reason)
    }
}
