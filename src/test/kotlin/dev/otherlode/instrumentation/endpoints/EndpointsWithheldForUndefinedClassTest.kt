/**
 * Drives endpoint withholding end to end. A module declares two endpoints from inside the
 * transform of a class whose supertype cannot be defined. The endpoint pipeline commits them once
 * ByteBuddy has produced the bytes, `defineClass` then raises `NoClassDefFoundError`, and
 * [LoadedClassSweep] passes withhold the endpoints for good instead of publishing them at zero
 * forever.
 *
 * The fixture classes are generated bytecode and never exist as `.class` files. Gradle's JUnit
 * Platform discovery loads every compiled test class through the application classloader, and a
 * class defined there is already in the JVM's loaded set when the sweep looks, whatever this
 * test's own loader did. See [dev.otherlode.instrumentation.ProbesWithheldForUndefinedClassTest].
 */
class EndpointsWithheldForUndefinedClassTest {
    private val instrumentation: Instrumentation = ByteBuddyAgent.install()
    private var installed: EndpointInstrumentation? = null
    private var installedTransformer: ResettableClassFileTransformer? = null

    private companion object {
        const val PACKAGE = "com.example.endpointtarget"
        const val VANISHING_BASE = "$PACKAGE.VanishingBase"
        const val VANISHING_SUB = "$PACKAGE.VanishingSub"
        const val STEADY_BASE = "$PACKAGE.SteadyBase"
        const val STEADY_SUB = "$PACKAGE.SteadySub"
        const val SLOW_BASE = "$PACKAGE.SlowBase"
        const val SLOW_SUB = "$PACKAGE.SlowSub"

        private fun internalName(dotted: String) = dotted.replace('.', '/')

        private fun classExtending(
            name: String,
            superName: String,
        ): ByteArray {
            val writer = ClassWriter(0)
            writer.visit(Opcodes.V17, Opcodes.ACC_PUBLIC or Opcodes.ACC_SUPER, internalName(name), null, internalName(superName), null)
            writer.visitEnd()
            return writer.toByteArray()
        }

        private val CLASS_BYTES: Map<String, ByteArray> =
            mapOf(
                VANISHING_BASE to classExtending(VANISHING_BASE, "java.lang.Object"),
                VANISHING_SUB to classExtending(VANISHING_SUB, VANISHING_BASE),
                STEADY_BASE to classExtending(STEADY_BASE, "java.lang.Object"),
                STEADY_SUB to classExtending(STEADY_SUB, STEADY_BASE),
                SLOW_BASE to classExtending(SLOW_BASE, "java.lang.Object"),
                SLOW_SUB to classExtending(SLOW_SUB, SLOW_BASE),
            )

        fun templatesOf(className: String): List<String> =
            listOf("/${className.substringAfterLast('.')}/a", "/${className.substringAfterLast('.')}/b")

        fun keyOf(
            className: String,
            template: String,
        ) = "$className#$template"
    }

    /**
     * Declares two endpoints for every class named `*Sub` under [PACKAGE], from inside its
     * transform, the way a module that reads routes off a class's annotations does.
     */
    private class DeclaringFromTransformModule : EndpointModule {
        override val name: String = "declaring-from-transform-${System.nanoTime()}"

        override fun typeMatcher(): ElementMatcher<in TypeDescription> =
            nameStartsWith<TypeDescription>("$PACKAGE.").and(nameEndsWith("Sub"))

        override fun transform(
            builder: DynamicType.Builder<*>,
            typeDescription: TypeDescription,
            advice: AdviceBinder,
            classLoader: ClassLoader?,
        ): DynamicType.Builder<*> {
            for (template in templatesOf(typeDescription.name)) {
                OtherlodeEndpoints.register(
                    name,
                    keyOf(typeDescription.name, template),
                    "GET",
                    template,
                    null,
                    typeDescription.name,
                    null,
                    null,
                )
            }
            return builder
        }
    }

    /**
     * Defines [CLASS_BYTES]'s classes from generated bytes, denying [deniedNames] in [loadClass]
     * while [getResourceAsStream] still serves their bytes, so ByteBuddy can describe and weave
     * the subclass and `defineClass` then fails on the supertype.
     */
    private class InMemoryDeniedSuperclassLoader(
        parent: ClassLoader,
        private val deniedNames: Set<String>,
    ) : ClassLoader(parent) {
        override fun loadClass(
            name: String,
            resolve: Boolean,
        ): Class<*> {
            if (name in deniedNames) throw ClassNotFoundException(name)
            val bytes = CLASS_BYTES[name] ?: return super.loadClass(name, resolve)
            synchronized(getClassLoadingLock(name)) {
                val loaded = findLoadedClass(name) ?: defineClass(name, bytes, 0, bytes.size)
                if (resolve) resolveClass(loaded)
                return loaded
            }
        }

        override fun getResourceAsStream(name: String): InputStream? {
            val dotted = name.removeSuffix(".class").replace('/', '.')
            return CLASS_BYTES[dotted]?.inputStream() ?: super.getResourceAsStream(name)
        }
    }

    /** Supplies [SLOW_BASE] only after [release] opens, and opens [stalled] when the JVM first asks for it. */
    private class StallingSuperclassLoader(
        parent: ClassLoader,
        private val stalled: CountDownLatch,
        private val release: CountDownLatch,
    ) : ClassLoader(parent) {
        override fun loadClass(
            name: String,
            resolve: Boolean,
        ): Class<*> {
            if (name == SLOW_BASE) {
                stalled.countDown()
                release.await()
            }
            val bytes = CLASS_BYTES[name] ?: return super.loadClass(name, resolve)
            synchronized(getClassLoadingLock(name)) {
                val loaded = findLoadedClass(name) ?: defineClass(name, bytes, 0, bytes.size)
                if (resolve) resolveClass(loaded)
                return loaded
            }
        }

        override fun getResourceAsStream(name: String): InputStream? {
            val dotted = name.removeSuffix(".class").replace('/', '.')
            return CLASS_BYTES[dotted]?.inputStream() ?: super.getResourceAsStream(name)
        }
    }

    private val config = AgentConfig.parse("includePackages=$PACKAGE")

    private fun freshLoader() = InMemoryDeniedSuperclassLoader(javaClass.classLoader, setOf(VANISHING_BASE))

    private fun install(registry: EndpointRegistry) {
        val endpointInstrumentation = EndpointInstrumentation(registry, listOf(DeclaringFromTransformModule()))
        installed = endpointInstrumentation
        installedTransformer = endpointInstrumentation.install(instrumentation)
    }

    private fun sweepFor(registry: EndpointRegistry) = LoadedClassSweep(instrumentation, ProbeRegistry(), registry, config)

    private fun EndpointRegistry.published(): List<String> =
        computeManifestEntries(100)
            .flatMap {
                it.endpoints
            }.map { it.routeTemplate }
            .sorted()

    @AfterTest
    fun tearDown() {
        val transformer = installedTransformer
        if (transformer != null) installed?.uninstall(instrumentation, transformer)
        installed = null
        installedTransformer = null
    }

    private fun captureLogRecords(
        loggerName: String,
        block: () -> Unit,
    ): List<JulLogRecord> {
        val records = mutableListOf<JulLogRecord>()
        val handler =
            object : JulHandler() {
                override fun publish(record: JulLogRecord) {
                    records += record
                }

                override fun flush() {}

                override fun close() {}
            }
        val julLogger = JulLogger.getLogger(loggerName)
        val originalLevel = julLogger.level
        julLogger.addHandler(handler)
        julLogger.level = JulLevel.ALL
        try {
            block()
        } finally {
            julLogger.removeHandler(handler)
            julLogger.level = originalLevel
        }
        return records
    }

    @Test
    fun `endpoints declared by a class that never defines are bound, withheld for good, named once and in no manifest`() {
        val registry = EndpointRegistry()
        install(registry)
        val sweep = sweepFor(registry)
        val loader = freshLoader()

        assertFailsWith<NoClassDefFoundError> { Class.forName(VANISHING_SUB, true, loader) }

        assertEquals(2, registry.endpoints().size, "the transform committed its endpoints before the definition failed")
        for (template in templatesOf(VANISHING_SUB)) {
            assertNotNull(registry.lookup(keyOf(VANISHING_SUB, template)), "the key is bound, so a hit would count")
        }
        assertEquals(emptyList(), registry.published(), "nothing is published before a sweep")
        assertEquals(1, registry.unconfirmedClassCount())

        val records =
            captureLogRecords(LoadedClassSweep::class.java.name) {
                sweep.run(runForwardPass = false)
                assertEquals(emptyList(), registry.published())
                sweep.run(runForwardPass = false)
                assertEquals(emptyList(), registry.published())
                sweep.run(runForwardPass = false)
                assertEquals(emptyList(), registry.published())
            }
        Reference.reachabilityFence(loader)

        val warnings = records.filter { it.level == JulLevel.WARNING && it.message.contains(VANISHING_SUB) }
        assertEquals(1, warnings.size, "a class withheld for good is named once and never again")
        assertTrue(warnings.single().message.contains("declared 2 endpoints"), warnings.single().message)
        assertEquals(1, registry.withheldForGoodClassCount())
        assertEquals(0, registry.unconfirmedClassCount())
        assertEquals(2, registry.endpoints().size)
        for (template in templatesOf(VANISHING_SUB)) {
            assertNotNull(registry.lookup(keyOf(VANISHING_SUB, template)), "withholding does not unbind a key")
        }
    }

    @Test
    fun `the same class defined successfully is published after one sweep`() {
        val registry = EndpointRegistry()
        install(registry)
        val sweep = sweepFor(registry)
        val loader = freshLoader()

        Class.forName(STEADY_SUB, true, loader)

        assertEquals(emptyList(), registry.published(), "nothing is published before the class is confirmed")
        sweep.run(runForwardPass = false)
        Reference.reachabilityFence(loader)

        assertEquals(templatesOf(STEADY_SUB), registry.published())
        assertEquals(0, registry.unconfirmedClassCount())
        assertEquals(0, registry.withheldForGoodClassCount())
    }

    @Test
    fun `a hit on one endpoint of a class publishes both before any sweep`() {
        val registry = EndpointRegistry()
        install(registry)
        val loader = freshLoader()
        Class.forName(STEADY_SUB, true, loader)
        val (first) = templatesOf(STEADY_SUB)

        registry.lookup(keyOf(STEADY_SUB, first))!!.hit()

        assertEquals(templatesOf(STEADY_SUB), registry.published(), "a hit confirms the class for its other endpoint too")
        Reference.reachabilityFence(loader)
    }

    @Test
    fun `an endpoint of a class that never defines is published when a runtime registration also reaches it`() {
        val registry = EndpointRegistry()
        install(registry)
        val sweep = sweepFor(registry)
        val loader = freshLoader()
        assertFailsWith<NoClassDefFoundError> { Class.forName(VANISHING_SUB, true, loader) }
        val (shared, own) = templatesOf(VANISHING_SUB)

        val records =
            captureLogRecords(LoadedClassSweep::class.java.name) {
                repeat(3) { sweep.run(runForwardPass = false) }
                registry.register(key = "runtime", framework = "fake", verb = "GET", verbatimTemplate = shared)
            }
        Reference.reachabilityFence(loader)

        assertEquals(listOf(shared), registry.published(), "the runtime registration confirms the one it reached")
        assertTrue(own !in registry.published())
        assertTrue(records.single { it.message.contains(VANISHING_SUB) }.message.contains("declared 2 endpoints"))
    }

    @Test
    fun `a class whose loader stalls on its supertype is never named, and is published once it defines`() {
        val registry = EndpointRegistry()
        install(registry)
        val sweep = sweepFor(registry)
        val stalled = CountDownLatch(1)
        val release = CountDownLatch(1)
        val loader = StallingSuperclassLoader(javaClass.classLoader, stalled, release)
        val defining = Thread({ Class.forName(SLOW_SUB, true, loader) }, "slow-definer")
        defining.start()
        try {
            assertTrue(stalled.await(30, TimeUnit.SECONDS), "the JVM must reach the supertype lookup")
            assertEquals(2, registry.endpoints().size, "the transform runs before the supertype lookup")

            val records =
                captureLogRecords(LoadedClassSweep::class.java.name) {
                    repeat(6) { sweep.run(runForwardPass = false) }
                }

            assertTrue(records.none { it.message.contains(SLOW_SUB) }, "a class still being defined is never named")
            assertEquals(0, registry.withheldForGoodClassCount())
            assertEquals(1, registry.unconfirmedClassCount(), "it stays pending while its definition runs")
            assertEquals(emptyList(), registry.published())
        } finally {
            release.countDown()
            defining.join(30_000)
        }

        sweep.run(runForwardPass = false)
        Reference.reachabilityFence(loader)

        assertEquals(0, registry.unconfirmedClassCount())
        assertEquals(templatesOf(SLOW_SUB), registry.published())
    }
}
